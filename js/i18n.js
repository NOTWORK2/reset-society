  const KEY = "rs-lang";
  let lang = null;
  try {
    const p = new URLSearchParams(location.search).get("lang");
    if (p === "ar" || p === "en") localStorage.setItem(KEY, p);
    lang = localStorage.getItem(KEY);
  } catch (e) { /* storage blocked */ }
  if (lang !== "ar" && lang !== "en") {
    lang = (navigator.language || "").toLowerCase().startsWith("ar") ? "ar" : "en";
  }
  const isAr = lang === "ar";
  const html = document.documentElement;
  html.lang = lang;
  html.dir = isAr ? "rtl" : "ltr";

  if (isAr) {
    const link = document.createElement("link");
    link.rel = "stylesheet";
    link.href = "https://fonts.googleapis.com/css2?family=IBM+Plex+Sans+Arabic:wght@300;400;500&family=Noto+Naskh+Arabic:wght@400;500&display=swap";
    document.head.appendChild(link);
  }

  function t(key, vars) {
    let s = DICT[lang][key];
    if (s === undefined) s = DICT.en[key];
    if (s === undefined) return key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
    return s;
  }

  function apply(root) {
    root = root || document;
    root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
    root.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
    root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
    root.querySelectorAll("[data-i18n-title]").forEach((el) => {
      const s = t(el.dataset.i18nTitle);
      document.title = s.includes("Reset Society") ? s : s + " | Reset Society";
    });
  }

  function setLang(l) {
    try { localStorage.setItem(KEY, l); } catch (e) { /* ignore */ }
    const url = new URL(location.href);
    url.searchParams.delete("lang");
    // Keep the language choice even when storage is blocked.
    if (l === "ar") url.searchParams.set("lang", "ar"); else url.searchParams.set("lang", "en");
    location.replace(url.toString());
  }

  window.RS_I18N = {
    lang,
    isAr,
    t,
    tIn: (l, key) => (DICT[l] && DICT[l][key]) || DICT.en[key] || key,
    apply,
    setLang,
    // Dates and times always with Western digits, which is what UAE customers expect.
    locale: isAr ? "ar-AE-u-nu-latn" : "en-GB",
    field: (obj, name) => (isAr && obj[name + "_ar"]) || obj[name],
    num: (n) => (typeof n === "number" ? new Intl.NumberFormat("en-US", { maximumFractionDigits: 2 }).format(n) : n),
    money: (n) => `${typeof n === "number" ? new Intl.NumberFormat("en-US", { maximumFractionDigits: 2 }).format(n) : n} ${t("currency")}`,
    // "4 Sessions" / Arabic plural rules: جلسة واحدة، جلستان، 3–10 جلسات، 11+ جلسة
    sessions(n) {
      if (!isAr) return `${n} ${n === 1 ? "Session" : "Sessions"}`;
      if (n === 1) return "جلسة واحدة";
      if (n === 2) return "جلستان";
      return n >= 3 && n <= 10 ? `${n} جلسات` : `${n} جلسة`;
    },
    time(hhmm) {
      const [h24, m] = hhmm.split(":").map(Number);
      const h = h24 % 12 || 12;
      const mm = String(m).padStart(2, "0");
      return isAr ? `${h}:${mm} ${h24 >= 12 ? "م" : "ص"}` : `${h}:${mm} ${h24 >= 12 ? "PM" : "AM"}`;
    }
  };

  document.addEventListener("DOMContentLoaded", () => {
    apply();
    document.querySelectorAll("[data-lang-toggle]").forEach((b) => {
      b.textContent = t("lang.switch");
      b.setAttribute("aria-label", t("lang.switchAria"));
      b.setAttribute("lang", isAr ? "en" : "ar");
      b.addEventListener("click", (e) => { e.preventDefault(); setLang(isAr ? "en" : "ar"); });
    });
  });
